#!/usr/bin/env node
// Stamps api/_build-info.js (gitignored) with commit / branch / buildTime so
// /api/version stays traceable even on CLI-promoted deploys where Vercel's
// VERCEL_GIT_* env vars are blank. Runs automatically via the npm "prebuild"
// hook, so plain `npm run build` (locally or on Vercel) always refreshes it.
//
// Resolution order per field:
//   commit: RELEASE_COMMIT → VERCEL_GIT_COMMIT_SHA → `git rev-parse HEAD` → null
//   branch: RELEASE_BRANCH → VERCEL_GIT_COMMIT_REF → `git rev-parse --abbrev-ref HEAD` → null
//
// On a Vercel *remote* build from a CLI upload there is no .git directory and
// no git env vars, so commit/branch come out null unless passed explicitly:
//   vercel deploy --build-env RELEASE_COMMIT=$(git rev-parse HEAD) \
//                 --build-env RELEASE_BRANCH=$(git branch --show-current)

import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function git(args) {
  try {
    const out = execSync(`git ${args}`, {
      cwd: root,
      stdio: ["ignore", "pipe", "ignore"],
    })
      .toString()
      .trim();
    return out || null;
  } catch {
    return null;
  }
}

const commit =
  process.env.RELEASE_COMMIT ||
  process.env.VERCEL_GIT_COMMIT_SHA ||
  git("rev-parse HEAD");

let branch =
  process.env.RELEASE_BRANCH ||
  process.env.VERCEL_GIT_COMMIT_REF ||
  git("rev-parse --abbrev-ref HEAD");
if (branch === "HEAD") branch = null; // detached HEAD is not a branch name

const buildTime = new Date().toISOString();

const info = { commit, branch, buildTime };
const contents = `// AUTO-GENERATED by scripts/generate-build-info.mjs — do not edit, do not commit.
export default ${JSON.stringify(info, null, 2)};
`;

const outPath = join(root, "api", "_build-info.js");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, contents);
console.log(
  `[build-info] commit=${commit ?? "unknown"} branch=${branch ?? "unknown"} buildTime=${buildTime}`
);
